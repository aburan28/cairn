"""Pre-registered test statistic: a seeded paired permutation test.

The shape every `statistical` verifier has. Two properties make it usable as a
unit of account, and both are unusual enough to be worth stating.

**It is pinned before the data exists.** This file's SHA-256 is inside the
objective, and the objective's id is a hash of its own content, so the
rejection rule cannot be chosen after seeing the numbers. Picking the test that
happens to clear on the data you already collected -- the oldest fraud in
empirical work, and the one that peer review is worst at catching -- requires
posting a *different* objective, which has funded nothing and which nobody has
cited.

**It is bit-reproducible.** Every node that runs it gets the identical integer,
so two honest verifiers cannot disagree. Three decisions buy that:

- The sign flips come from a SplitMix64 written out longhand rather than from
  `random`. CPython's Mersenne Twister is stable in practice, but "in practice"
  is not a specification, and a Rust or Go node re-deriving this settlement has
  no obligation to reproduce it. Sixteen lines of arithmetic have no such
  ambiguity.
- The seed arrives from the objective, never from the artifact. A submitter who
  could choose the randomisation could grind seeds until one cleared.
- No floats, anywhere. IEEE-754 sums do not reproduce bitwise across hardware,
  and a p-value that differs in the last bit across two nodes is a p-value that
  can straddle the threshold. The result is parts per million as an integer,
  rounded *up*, so rounding can only ever make acceptance harder.
"""

MASK = (1 << 64) - 1
ROUNDS = 20_000
SCALE = 1_000_000
MIN_PAIRS = 20
MAX_PAIRS = 1_000
MAX_MAGNITUDE = 10**9


class SplitMix64:
    """Sebastiano Vigna's SplitMix64. Chosen because it is short enough to
    re-implement correctly from this file alone, which is the property that
    matters here -- statistical quality beyond that is irrelevant for sign
    flips."""

    def __init__(self, seed: int) -> None:
        self.state = seed & MASK

    def next_u64(self) -> int:
        self.state = (self.state + 0x9E3779B97F4A7C15) & MASK
        z = self.state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        return z ^ (z >> 31)


def _differences(artifact: dict) -> list[int]:
    observations = artifact.get("observations")
    if not isinstance(observations, list):
        raise ValueError("artifact.observations must be a list of [control, treatment] pairs")
    if not MIN_PAIRS <= len(observations) <= MAX_PAIRS:
        raise ValueError(f"need between {MIN_PAIRS} and {MAX_PAIRS} paired observations")
    differences = []
    for pair in observations:
        if not isinstance(pair, list) or len(pair) != 2:
            raise ValueError("each observation must be a [control, treatment] pair")
        control, treatment = pair
        for value in (control, treatment):
            # bool is an int in Python, and `True` as a measurement is a sign
            # the artifact was generated rather than measured.
            if isinstance(value, bool) or not isinstance(value, int):
                raise ValueError("measurements must be integers; scale fractional units")
            if abs(value) > MAX_MAGNITUDE:
                raise ValueError("measurement magnitude is implausible")
        differences.append(treatment - control)
    return differences


def statistic(artifact: dict, seed: int) -> int:
    """Two-sided paired permutation p-value, in parts per million.

    Under the null the treatment label is exchangeable within each pair, so the
    reference distribution is generated by flipping the sign of each difference
    independently. Returns `ceil((hits + 1) / (ROUNDS + 1) * 1e6)`; the `+1`
    on both sides is the standard Monte Carlo correction, which keeps the
    p-value from ever being reported as exactly zero on a finite number of
    rounds.
    """
    differences = _differences(artifact)
    observed = abs(sum(differences))
    rng = SplitMix64(seed)

    hits = 0
    bits = 0
    available = 0
    for _ in range(ROUNDS):
        total = 0
        for difference in differences:
            if available == 0:
                bits = rng.next_u64()
                available = 64
            total += difference if bits & 1 else -difference
            bits >>= 1
            available -= 1
        if abs(total) >= observed:
            hits += 1

    # Integer ceiling division: rounding a p-value up can only make an
    # objective harder to clear, which is the safe direction for money.
    return ((hits + 1) * SCALE + ROUNDS) // (ROUNDS + 1)
