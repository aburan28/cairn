    fn a_proof_verifies_and_a_forged_one_does_not() {
        let seed = b"epoch 12345";
        let proof = prove(seed, 512);
        assert!(verify(seed, 512, &proof));

        // A different seed is a different beacon. This is the property that
        // stops a sequencer reusing one epoch's answer in another.
        assert!(!verify(b"epoch 12346", 512, &proof));

        // A different difficulty is a different beacon too, which is why `T`
        // is inside the Fiat-Shamir transcript: without it, a prover computes
        // an honest proof cheaply at T = 1 and presents it for T = 2^30.
        assert!(!verify(seed, 511, &proof));
        assert!(!verify(seed, 1024, &proof));
    }

    #[test]
    fn the_output_cannot_be_edited_without_the_proof_failing() {
        let seed = b"grind me";
        let mut proof = prove(seed, 256);
        assert!(verify(seed, 256, &proof));

        // Flipping one bit of the answer. A sequencer that wants a different
        // beacon has to redo the delay, which is the entire point.
        proof.output[ELEMENT_BYTES - 1] ^= 1;
        assert!(!verify(seed, 256, &proof));

        // And the witness is not free to choose either.
        let mut proof = prove(seed, 256);
        proof.witness[0] ^= 0x80;
        assert!(!verify(seed, 256, &proof));
    }

    #[test]
    fn an_element_out_of_range_is_refused_rather_than_reduced() {
        // A value at or above the modulus is not a group element. Reducing it
        // silently would give two encodings of one beacon, and a record whose
        // canonical form is not a function of its meaning.
        let seed = b"range";
        let proof = prove(seed, 64);
        let mut oversized = proof.clone();
        oversized.output = modulus().to_be_bytes(ELEMENT_BYTES);
        assert!(!verify(seed, 64, &oversized));

        // Wrong width is refused before any arithmetic.
        let mut short = proof.clone();
        short.output.truncate(ELEMENT_BYTES - 1);
        assert!(!verify(seed, 64, &short));
    }

